    public void setMemberDetailsToTable(){
        try {
            Statement st=con1.createStatement();
            ResultSet rs=st.executeQuery("SELECT * FROM MANAGEMEMBERS");
            
            while(rs.next()){
                int memberId=rs.getInt("MEMBER_ID");
                String memberName=rs.getString("MEMBER");
                String profession=rs.getString("PROFESSION");
                String phoneNo=rs.getString("PHONE");
                
                Object[] obj={memberId,memberName,profession,phoneNo};
                model= (DefaultTableModel) tbl_memberDetails.getModel();
                model.addRow(obj);
            }
        } catch (SQLException ex) {
            Logger.getLogger(ManageBooks.class.getName()).log(Level.SEVERE, null, ex);
        }
          
    }
