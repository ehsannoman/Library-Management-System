    public void setBookDetailsToTable(){
        try {
            Statement st=con.createStatement();
            ResultSet rs=st.executeQuery("SELECT * FROM MANAGEBOOKS");
            
            while(rs.next()){
                String bookId=rs.getString("BOOK_ID");
                String bookName=rs.getString("BOOK");
                String authorName=rs.getString("AUTHOR");
                int quantities=rs.getInt("QUANTITY");
                
                Object[] obj={bookId,bookName,authorName,quantities};
                model= (DefaultTableModel) tbl_bookdetails.getModel();
                model.addRow(obj);
            }
        } catch (SQLException ex) {
            Logger.getLogger(ManageBooks.class.getName()).log(Level.SEVERE, null, ex);
        }
          
    }
    
    public boolean addBook(){
        boolean isAdded=false;
        book_id=Integer.parseInt(txt_bookId.getText());
        book= txt_bookName.getText();
        author=txt_authorName.getText();
        quantity=Integer.parseInt(txt_quantity.getText());
        
        try{
            String sql = "INSERT INTO MANAGEBOOKS (BOOK_ID,BOOK,AUTHOR, QUANTITY) VALUES (?, ?, ?, ?)";
            PreparedStatement ps = con.prepareStatement(sql);
            ps.setInt(1,book_id);
            ps.setString(2,book);
            ps.setString(3, author);
            ps.setInt(4, quantity);
            int rowCount=ps.executeUpdate();
            if(rowCount>0){
                isAdded=true;
            }
            else{
                isAdded=false;
            }
            
        }catch(Exception e){
            
        }
        return isAdded;
    }
    
    public boolean updateBook(){
        boolean isUpdated=false;
        book_id=Integer.parseInt(txt_bookId.getText());
        book= txt_bookName.getText();
        author=txt_authorName.getText();
        quantity=Integer.parseInt(txt_quantity.getText());
        
        try{
            String sql="UPDATE MANAGEBOOKS SET BOOK = ?, AUTHOR = ?,QUANTITY=? WHERE BOOK_ID = ?";
            PreparedStatement ps = con.prepareStatement(sql);
            
            ps.setString(1,book);
            ps.setString(2, author);
            ps.setInt(3, quantity);
            ps.setInt(4,book_id);
            
            int rowCount=ps.executeUpdate();
            if(rowCount>0){
                isUpdated=true;
            }
            else{
                isUpdated=false;
            }
        }catch(Exception e){
           
        }
        return isUpdated;
    }
    
    public boolean deleteBook(){
         boolean isDeleted=false;
        book_id=Integer.parseInt(txt_bookId.getText());
        
        try{
            String sql="DELETE FROM MANAGEBOOKS WHERE BOOK_ID = ?";
            PreparedStatement ps = con.prepareStatement(sql);
            ps.setInt(1,book_id);
            int rowCount=ps.executeUpdate();
            if(rowCount>0){
                isDeleted=true;
            }
            else{
                isDeleted=false;
            }
        }catch(Exception e){
            
        }
        return isDeleted;
    }
    
    public void clearTable(){
        DefaultTableModel model= (DefaultTableModel) tbl_bookdetails.getModel();
        model.setRowCount(0);
        
    }

