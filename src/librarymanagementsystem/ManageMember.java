    public void setMemberDetailsToTable(){
        try {
            Statement st=con.createStatement();
            ResultSet rs=st.executeQuery("SELECT * FROM MANAGEMEMBERS");
            
            while(rs.next()){
                int memberId=rs.getInt("MEMBER_ID");
                String memberName=rs.getString("MEMBER");
                String profession=rs.getString("PROFESSION");
                String phoneNo=rs.getString("PHONE");
                
                Object[] obj={memberId,memberName,profession,phoneNo};
                model= (DefaultTableModel) tbl_memberDetails.getModel();
                model.addRow(obj);
            }
        } catch (SQLException ex) {
            Logger.getLogger(ManageBooks.class.getName()).log(Level.SEVERE, null, ex);
        }
          
    }
    
    public boolean addMember(){
        boolean isAdded=false;
        member_id=Integer.parseInt(txt_memberId.getText());
        member= txt_memberName.getText();
        profession=txt_profession.getText();
        phone=txt_contactNo.getText();
        
        try{
            String sql = "INSERT INTO MANAGEMEMBERS (MEMBER_ID,MEMBER,PROFESSION, PHONE) VALUES (?, ?, ?, ?)";
            PreparedStatement ps = con.prepareStatement(sql);
            ps.setInt(1,member_id);
            ps.setString(2,member);
            ps.setString(3, profession);
            ps.setString(4, phone);
            int rowCount=ps.executeUpdate();
            if(rowCount>0){
                isAdded=true;
            }
            else{
                isAdded=false;
            }
            
        }catch(Exception e){
            
        }
        return isAdded;
    }
    
    public boolean updateBook(){
        boolean isUpdated=false;
        member_id=Integer.parseInt(txt_memberId.getText());
        member= txt_memberName.getText();
        profession=txt_profession.getText();
        phone=txt_contactNo.getText();
        
        try{
            String sql="UPDATE MANAGEMEMBERS SET MEMBER = ?, PROFESSION = ?,PHONE=? WHERE MEMBER_ID = ?";
            PreparedStatement ps = con.prepareStatement(sql);
            
            ps.setString(1,member);
            ps.setString(2,profession);
            ps.setString(3, phone);
            ps.setInt(4,member_id);
            
            int rowCount=ps.executeUpdate();
            if(rowCount>0){
                isUpdated=true;
            }
            else{
                isUpdated=false;
            }
        }catch(Exception e){
           
        }
        return isUpdated;
    }
    
    public boolean deleteMember(){
         boolean isDeleted=false;
         member_id=Integer.parseInt(txt_memberId.getText());
        
        try{
            String sql="DELETE FROM MANAGEMEMBERS WHERE MEMBER_ID = ?";
            PreparedStatement ps = con.prepareStatement(sql);
            ps.setInt(1,member_id);
            int rowCount=ps.executeUpdate();
            if(rowCount>0){
                isDeleted=true;
            }
            else{
                isDeleted=false;
            }
        }catch(Exception e){
            
        }
        return isDeleted;
    }
    
    public void clearTable(){
        DefaultTableModel model= (DefaultTableModel) tbl_memberDetails.getModel();
        model.setRowCount(0);
        
    }

