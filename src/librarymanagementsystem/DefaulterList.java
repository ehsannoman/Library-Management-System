    public void setIssueBookDetailsToTable(){
        long l= System.currentTimeMillis();
        Date todaysDate=new Date(l);
        try {
            PreparedStatement ps=con.prepareStatement("SELECT * FROM ISSUEBOOKS WHERE RETURN_DATE<? AND STATUS=?");
            ps.setDate(1, todaysDate);
            ps.setString(2, "Pending");
            ResultSet rs=ps.executeQuery();
            
            while(rs.next()){
                String id=rs.getString("IID");
                String bookName=rs.getString("BOOK");
                String memberName=rs.getString("MEMBER");
                String issueDate=rs.getString("ISSUE_DATE");
                String returnDate=rs.getString("RETURN_DATE");
                String status=rs.getString("STATUS");
                
                Object[] obj={id,bookName,memberName,issueDate,returnDate,status};
                model= (DefaultTableModel) tbl_issueBookDetails.getModel();
                model.addRow(obj);
            }
        } catch (SQLException ex) {
            Logger.getLogger(ManageBooks.class.getName()).log(Level.SEVERE, null, ex);
        }
          
    }

