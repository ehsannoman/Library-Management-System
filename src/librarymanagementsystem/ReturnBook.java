    public void getIssueBookDetails(){
            
            int bookId=Integer.parseInt(txt_bookId.getText());
            int memberId=Integer.parseInt(txt_memberId.getText());
        try {
            PreparedStatement ps=con.prepareStatement("SELECT * FROM ISSUEBOOKS WHERE BOOK_ID = ? AND MEMBER_ID=? AND STATUS=?");
            ps.setInt(1,bookId);
            ps.setInt(2,memberId);
            ps.setString(3,"Pending");
            ResultSet rs=ps.executeQuery();
            
            if(rs.next()){
                
                lbl_issueId.setText(rs.getString("IID"));
                lbl_bookName.setText(rs.getString("BOOK"));
                lbl_memberName.setText(rs.getString("MEMBER"));
                lbl_issueDate.setText(rs.getString("ISSUE_DATE"));
                lbl_returnDate.setText(rs.getString("RETURN_DATE"));
                lbl_bookerror.setText("");
            }
            else{
                lbl_bookerror.setText("No record found !!!");
                lbl_issueId.setText(null); 
                lbl_bookName.setText(null); 
                lbl_memberName.setText(null); 
                lbl_issueDate.setText(null); 
                lbl_returnDate.setText(null); 
                
                
            }
        } catch (SQLException ex) {
            Logger.getLogger(IssueBook.class.getName()).log(Level.SEVERE, null, ex);
        }
        
    }
    
    public boolean returnBook(){
        boolean isReturned=false;
        int bookId=Integer.parseInt(txt_bookId.getText());
        int memberId=Integer.parseInt(txt_memberId.getText());
        try{
            String sql="UPDATE ISSUEBOOKS SET STATUS=? WHERE BOOK_ID = ? AND MEMBER_ID=? AND STATUS=?";
            PreparedStatement ps = con.prepareStatement(sql);
            ps.setString(1, "Returned");
            ps.setInt(2,bookId);
            ps.setInt(3,memberId);
            ps.setString(4, "Pending");
            
            int rowCount=ps.executeUpdate();
            if(rowCount>0){
                isReturned=true;
            }
            else{
                isReturned=false;
               
            }
            }catch(Exception e){
            
        } 
        return isReturned;
    }
    
    public void updateBookCount(){
        int bookId= Integer.parseInt(txt_bookId.getText());
        try{
            String sql="UPDATE MANAGEBOOKS SET QUANTITY=QUANTITY+1 WHERE BOOK_ID = ?";
            PreparedStatement ps = con1.prepareStatement(sql);
            ps.setInt(1,bookId);
            int rowCount=ps.executeUpdate();
            if(rowCount>0){
                JOptionPane.showMessageDialog(this,"Book count updated!");
            }
            else{
                JOptionPane.showMessageDialog(this,"Book count update failed!");
            }
        }catch(Exception e){
           
        }
    }  
    
    

